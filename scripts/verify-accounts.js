import 'dotenv/config';
import '../src/database/environment.js';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import request from 'supertest';
import supabase from '../api/db-client.js';
import { createApp } from '../src/app.js';
import { createRepository } from '../src/database/repository.js';
import { createAccountRepository } from '../src/database/account.repository.js';
import { createAccountService } from '../src/services/account.service.js';
import { sessionHash } from '../src/utils/account-session.js';
const api = request(createApp(createRepository(supabase), createAccountService(createAccountRepository(supabase))));
const login = async identifier => (await api.post('/api/auth/login').send({ identifier, password: 'Fairshare2026!' }).expect(200)).body;
const headers = token => ({ Authorization: `Bearer ${token}` });
let a, b, friendSession;
try {
  a = await login('fairshare_demo'); b = await login('DEMO@FAIRSHARE.EXAMPLE');
  assert.match(a.token, /^[A-Za-z0-9_-]{43}$/);
  const aContext = await createAccountRepository(supabase).authorize(a.token);
  const storedA = await supabase.from('c4_account_sessions').select('*').eq('token_hash', sessionHash(a.token)).single();
  assert.equal(storedA.error, null); assert.ok(!JSON.stringify(storedA.data).includes(a.token)); assert.ok(!JSON.stringify(storedA.data).includes(aContext.nativeToken));
  const friend = await api.post('/api/auth/login').send({ identifier: 'travel_friend', password: 'TravelFriend2026!' }).expect(200); friendSession = friend.body;
  assert.notEqual(a.token, b.token);
  assert.deepEqual((await api.get('/api/auth/me').set(headers(a.token)).expect(200)).body, { id: 1, username: 'fairshare_demo', email: 'demo@fairshare.example' });
  const unknown = await api.post('/api/auth/login').send({ identifier: 'unknown_' + randomBytes(4).toString('hex'), password: 'WrongPassword123' }).expect(401);
  const wrong = await api.post('/api/auth/login').send({ identifier: 'fairshare_demo', password: 'WrongPassword123' }).expect(401);
  assert.deepEqual(unknown.body, { error: 'Invalid credentials' }); assert.deepEqual(wrong.body, unknown.body);
  await api.post('/api/auth/register').send({ username: 'FAIRSHARE_DEMO', email: 'different@example.test', password: 'GoodPassword2026' }).expect(409);
  await api.post('/api/auth/register').send({ username: 'different_user', email: 'DEMO@FAIRSHARE.EXAMPLE', password: 'GoodPassword2026' }).expect(409);
  await api.post('/api/friends').set(headers(b.token)).send({ username: '@fairshare_demo' }).expect(400);
  await api.post('/api/friends').set(headers(b.token)).send({ username: '@missing_' + randomBytes(5).toString('hex') }).expect(404);
  const before = (await api.get('/api/friends').set(headers(b.token)).expect(200)).body;
  if (before.some(friend => friend.id === 2)) await api.delete('/api/friends/2').set(headers(b.token)).expect(204);
  await api.delete('/api/friends/2').set(headers(b.token)).expect(404);
  const added = await api.post('/api/friends').set(headers(b.token)).send({ username: '@TRAVEL_FRIEND' }).expect(201); assert.deepEqual(added.body, { id: 2, username: 'travel_friend' });
  await api.post('/api/friends').set(headers(b.token)).send({ username: 'travel_friend' }).expect(409);
  assert.deepEqual((await api.get('/api/friends').set(headers(friendSession.token)).expect(200)).body, []);
  const context = await createAccountRepository(supabase).authorize(b.token);
  assert.ok(context.nativeUser.user_metadata.fairshare_friends.some(friend => friend.username === 'travel_friend'));
  const profiles = await supabase.from('c4_account_profiles').select('email'); assert.equal(profiles.error, null); assert.ok(profiles.data.every(profile => profile.email === ''));
  const sqlFriends = await supabase.from('c4_account_friends').select('*'); assert.equal(sqlFriends.error, null); assert.deepEqual(sqlFriends.data, []);
  console.log('PASS: real username/email login, identical 401 failures, duplicate registration 409, private-provider saved friends, add/remove/self/unknown/duplicate behavior, and friend-list isolation.');
  await api.post('/api/auth/logout').set(headers(a.token)).expect(204);
  await api.get('/api/auth/me').set(headers(a.token)).expect(401);
  await api.get('/api/auth/me').set(headers(b.token)).expect(200);
  const direct = await context.client.auth.getUser(aContext.nativeToken); assert.ok(direct.error); assert.equal(direct.data.user, null);
  assert.equal((await supabase.from('c4_account_sessions').select('token_hash').eq('token_hash', sessionHash(a.token)).maybeSingle()).data, null);
  assert.ok((await supabase.from('c4_account_sessions').select('token_hash').eq('token_hash', sessionHash(b.token)).maybeSingle()).data);
  const restored = await supabase.from('c4_account_sessions').insert(storedA.data).select('*'); assert.equal(restored.error, null);
  await api.get('/api/auth/me').set(headers(a.token)).expect(401);
  await supabase.from('c4_account_sessions').delete().eq('token_hash', sessionHash(a.token));
  console.log('PASS: 32-byte opaque tokens, no plaintext bearers/provider JWTs in session rows, token A deleted and revoked natively (even after row restoration), and token B remains active.');
  await api.get('/api/groups/goa-with-the-gang-26').expect(200);
  await api.get('/api/groups/goa-with-the-gang-26/expenses').expect(200);
  await api.get('/api/groups/goa-with-the-gang-26/balances').expect(200);
  await api.get('/api/groups/goa-with-the-gang-26/settlements').expect(200);
  console.log('PASS: existing group reads still succeed with no Authorization header.');
  if (process.env.VERIFY_REGISTER === '1') {
    const username = `verify_${randomBytes(5).toString('hex')}`, email = `${username}@example.test`, password = `A${randomBytes(63).toString('hex')}1`;
    const registered = await api.post('/api/auth/register').send({ username, email, password }).expect(201);
    assert.deepEqual(Object.keys(registered.body).sort(), ['email', 'id', 'username']);
    const session = (await api.post('/api/auth/login').send({ identifier: email, password }).expect(200)).body;
    assert.equal(session.user.email, email);
    await api.post('/api/auth/register').send({ username: username.toUpperCase(), email: `new_${email}`, password }).expect(409);
    await api.post('/api/auth/register').send({ username: username + '_2', email: email.toUpperCase(), password }).expect(409);
    await api.post('/api/auth/logout').set(headers(session.token)).expect(204);
    console.log(`PASS: live registration and email login with a 128-character password. Disposable provider account ${username} is retained; this environment does not supply an Auth user-deletion tool.`);
  }
} finally {
  for (const session of [a, b, friendSession]) if (session) await api.post('/api/auth/logout').set(headers(session.token));
}
